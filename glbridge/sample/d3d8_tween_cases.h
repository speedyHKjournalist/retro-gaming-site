static void d3d8_tween_checks(void)
{
    DWORD baseline, recorded, both, missing, position_only, normal_only;
    const DWORD all[] = { D3DVSD_STREAM(15), D3DVSD_REG(D3DVSDE_POSITION, D3DVSDT_FLOAT3), D3DVSD_REG(D3DVSDE_NORMAL, D3DVSDT_FLOAT3), D3DVSD_STREAM(1), D3DVSD_REG(D3DVSDE_POSITION2, D3DVSDT_FLOAT3), D3DVSD_REG(D3DVSDE_NORMAL2, D3DVSDT_FLOAT3), D3DVSD_END() };
    const DWORD no_second[] = { D3DVSD_STREAM(15), D3DVSD_REG(D3DVSDE_POSITION, D3DVSDT_FLOAT3), D3DVSD_REG(D3DVSDE_NORMAL, D3DVSDT_FLOAT3), D3DVSD_END() };
    const DWORD p_second[] = { D3DVSD_STREAM(15), D3DVSD_REG(D3DVSDE_POSITION, D3DVSDT_FLOAT3), D3DVSD_REG(D3DVSDE_NORMAL, D3DVSDT_FLOAT3), D3DVSD_STREAM(1), D3DVSD_REG(D3DVSDE_POSITION2, D3DVSDT_FLOAT3), D3DVSD_END() };
    const DWORD n_second[] = { D3DVSD_STREAM(15), D3DVSD_REG(D3DVSDE_POSITION, D3DVSDT_FLOAT3), D3DVSD_REG(D3DVSDE_NORMAL, D3DVSDT_FLOAT3), D3DVSD_STREAM(1), D3DVSD_SKIP(3), D3DVSD_REG(D3DVSDE_NORMAL2, D3DVSDT_FLOAT3), D3DVSD_END() };
    check(SUCCEEDED(CALL(CreateStateBlock)(device, D3DSBT_ALL, &baseline)), "D3D8 tween baseline");
    check(SUCCEEDED(CALL(CreateVertexShader)(device, all, NULL, &both, 0)) && SUCCEEDED(CALL(CreateVertexShader)(device, no_second, NULL, &missing, 0)) && SUCCEEDED(CALL(CreateVertexShader)(device, p_second, NULL, &position_only, 0)) && SUCCEEDED(CALL(CreateVertexShader)(device, n_second, NULL, &normal_only, 0)), "D3D8 tween declarations");
    Buffer *primary, *secondary, *small, *output;
    float first[12] = { -.5f, 0, .25f, -1, 0, 0, -.25f, 0, .25f, -1, 0, 0 }, second[6] = { .5f, 0, .75f, 1, 0, 0 };
    create_buffer(0, sizeof(first), &primary);
    create_buffer(0, sizeof(second), &secondary);
    create_buffer(0, sizeof(second) - 1, &small);
    create_buffer(D3DFVF_XYZRHW | D3DFVF_DIFFUSE | D3DFVF_SPECULAR | D3DFVF_TEX1 | D3DFVF_TEXCOORDSIZE4(0), 2 * sizeof(Output), &output);
    CopyMemory(lock_buffer(primary), first, sizeof(first));
    check(SUCCEEDED(BUF(Unlock)(primary)), "D3D8 tween primary upload");
    CopyMemory(lock_buffer(secondary), second, sizeof(second));
    check(SUCCEEDED(BUF(Unlock)(secondary)), "D3D8 tween secondary upload");
    check(SUCCEEDED(CALL(SetStreamSource)(device, 15, primary, 24)) && SUCCEEDED(CALL(SetStreamSource)(device, 1, secondary, 0)) && SUCCEEDED(CALL(SetVertexShader)(device, both)), "D3D8 tween multi and constant streams");
    check(SUCCEEDED(CALL(SetStreamSource)(device, 0, NULL, 0)), "D3D8 tween needs no stream zero");
    D3DMATRIX matrix;
    identity(&matrix);
    matrix._11 = 2;
    check(SUCCEEDED(CALL(SetTransform)(device, D3DTS_WORLD, &matrix)), "D3D8 tween world");
    identity(&matrix);
    matrix._42 = .25f;
    check(SUCCEEDED(CALL(SetTransform)(device, D3DTS_VIEW, &matrix)), "D3D8 tween view");
    identity(&matrix);
    matrix._33 = .5f;
    check(SUCCEEDED(CALL(SetTransform)(device, D3DTS_PROJECTION, &matrix)), "D3D8 tween projection");
    Material material;
    ZeroMemory(&material, sizeof(material));
    material.Diffuse.r = material.Diffuse.g = material.Diffuse.b = material.Diffuse.a = 1;
    check(SUCCEEDED(CALL(SetMaterial)(device, &material)), "D3D8 tween material");
    Light lamp;
    ZeroMemory(&lamp, sizeof(lamp));
    lamp.Type = D3DLIGHT_DIRECTIONAL;
    lamp.Direction.x = -1;
    lamp.Diffuse.r = lamp.Diffuse.g = lamp.Diffuse.b = 1;
    light(&lamp);
    state(D3DRS_LIGHTING, TRUE);
    state(D3DRS_COLORVERTEX, FALSE);
    state(D3DRS_AMBIENT, 0);
    state(D3DRS_DIFFUSEMATERIALSOURCE, D3DMCS_MATERIAL);
    state(D3DRS_NORMALIZENORMALS, FALSE);
    state(D3DRS_SPECULARENABLE, FALSE);
    state(D3DRS_VERTEXBLEND, D3DVBF_TWEENING);
    state(D3DRS_INDEXEDVERTEXBLENDENABLE, TRUE);
    float_state(D3DRS_TWEENFACTOR, .75f);
    state(D3DRS_FOGVERTEXMODE, D3DFOG_LINEAR);
    state(D3DRS_RANGEFOGENABLE, FALSE);
    float_state(D3DRS_FOGSTART, 0);
    float_state(D3DRS_FOGEND, 1);
    state(D3DRS_CLIPPLANEENABLE, 0);
    state(D3DRS_CLIPPING, TRUE);
    texture_state(0x20000, 0);
    FillMemory(lock_buffer(output), 2 * sizeof(Output), 0xa5);
    check(SUCCEEDED(BUF(Unlock)(output)) && SUCCEEDED(CALL(ProcessVertices)(device, 0, 0, 2, output, 0)), "D3D8 tween ProcessVertices");
    Output result[2];
    CopyMemory(result, lock_buffer(output), sizeof(result));
    check(SUCCEEDED(BUF(Unlock)(output)), "D3D8 tween read output");
    check(result[0].x == 48 && result[1].x == 52 && result[0].y == 24 && result[0].z == .3125f && result[0].rhw == 1, "D3D8 tween affine position");
    check(result[0].diffuse == 0xff404040u && (result[0].specular >> 24) == 96 && result[0].tex[0] == .5f && result[0].tex[1] == .25f && result[0].tex[2] == .625f, "D3D8 tween lighting fog and generated coordinates");
    state(D3DRS_NORMALIZENORMALS, TRUE);
    check(SUCCEEDED(CALL(ProcessVertices)(device, 0, 0, 1, output, 0)), "D3D8 normalized tween process");
    Output value = *(Output*)lock_buffer(output);
    check(SUCCEEDED(BUF(Unlock)(output)) && value.diffuse == 0xffffffffu, "D3D8 tween normalization after interpolation");
    state(D3DRS_NORMALIZENORMALS, FALSE);
    check(SUCCEEDED(CALL(SetVertexShader)(device, normal_only)) && SUCCEEDED(CALL(ProcessVertices)(device, 0, 0, 1, output, 0)), "D3D8 normal-only tween process");
    value = *(Output*)lock_buffer(output);
    check(SUCCEEDED(BUF(Unlock)(output)) && value.x == 0 && value.diffuse == 0xff404040u, "D3D8 independent secondary normal");
    check(SUCCEEDED(CALL(SetVertexShader)(device, position_only)) && SUCCEEDED(CALL(ProcessVertices)(device, 0, 0, 1, output, 0)), "D3D8 position-only tween process");
    value = *(Output*)lock_buffer(output);
    check(SUCCEEDED(BUF(Unlock)(output)) && value.x == 48 && value.diffuse == 0xff000000u, "D3D8 independent secondary position");
    check(SUCCEEDED(CALL(SetVertexShader)(device, both)) && SUCCEEDED(CALL(BeginStateBlock)(device)), "D3D8 record tween factor");
    float_state(D3DRS_TWEENFACTOR, .25f);
    DWORD factor;
    check(SUCCEEDED(CALL(GetRenderState)(device, D3DRS_TWEENFACTOR, &factor)) && factor == 0x3f400000u && SUCCEEDED(CALL(EndStateBlock)(device, &recorded)) && SUCCEEDED(CALL(ApplyStateBlock)(device, recorded)) && SUCCEEDED(CALL(DeleteStateBlock)(device, recorded)), "D3D8 deferred tween factor");
    D3DCLIPSTATUS8 status = { 0, 0xffffffffu };
    float plane[4] = { 1, 0, 0, -.25f };
    check(SUCCEEDED(CALL(SetClipPlane)(device, 0, plane)) && SUCCEEDED(CALL(SetClipStatus)(device, &status)), "D3D8 tween plane");
    state(D3DRS_CLIPPLANEENABLE, 1);
    check(SUCCEEDED(CALL(ProcessVertices)(device, 0, 0, 2, output, 0)) && SUCCEEDED(CALL(GetClipStatus)(device, &status)) && (status.ClipUnion & D3DCS_PLANE0) && (status.ClipIntersection & D3DCS_PLANE0), "D3D8 tween user-plane ClipStatus");
    state(D3DRS_CLIPPLANEENABLE, 0);
    float_state(D3DRS_TWEENFACTOR, .75f);
    CopyMemory(lock_buffer(output), first, sizeof(first));
    check(SUCCEEDED(BUF(Unlock)(output)) && SUCCEEDED(CALL(SetStreamSource)(device, 15, output, 24)) && SUCCEEDED(CALL(ProcessVertices)(device, 0, 0, 2, output, 0)), "D3D8 aliased tween input");
    CopyMemory(result, lock_buffer(output), sizeof(result));
    check(SUCCEEDED(BUF(Unlock)(output)) && result[0].x == 48 && result[1].x == 52, "D3D8 tween snapshots aliased input before writes");
    FillMemory(lock_buffer(output), 2 * sizeof(Output), 0xa5);
    check(SUCCEEDED(BUF(Unlock)(output)) && SUCCEEDED(CALL(SetStreamSource)(device, 1, small, 0)) && FAILED(CALL(ProcessVertices)(device, 0, 0, 2, output, 0)), "D3D8 short secondary stream refused");
    check(SUCCEEDED(CALL(SetStreamSource)(device, 1, secondary, 0)) && SUCCEEDED(CALL(SetVertexShader)(device, missing)) && FAILED(CALL(ProcessVertices)(device, 0, 0, 2, output, 0)), "D3D8 missing tween channels refused");
    BYTE* bytes = lock_buffer(output);
    for (unsigned i = 0; i < 2 * sizeof(Output); ++i)
        check(bytes[i] == 0xa5, "D3D8 failed tween preserves output");
    check(SUCCEEDED(BUF(Unlock)(output)), "D3D8 atomic tween unlock");
    check(SUCCEEDED(CALL(ApplyStateBlock)(device, baseline)) && SUCCEEDED(CALL(DeleteStateBlock)(device, baseline)), "restore D3D8 tween baseline");
    check(SUCCEEDED(CALL(DeleteVertexShader)(device, both)) && SUCCEEDED(CALL(DeleteVertexShader)(device, missing)) && SUCCEEDED(CALL(DeleteVertexShader)(device, position_only)) && SUCCEEDED(CALL(DeleteVertexShader)(device, normal_only)), "D3D8 release tween declarations");
    BUF(Release)(primary);
    BUF(Release)(secondary);
    BUF(Release)(small);
    BUF(Release)(output);
    report("PASS D3D8 CPU tween: declaration/multi/constant inputs, independent position/normal, lighting/fog/texgen, state-block factor, user-plane ClipStatus, alias snapshot and atomic failure");
}

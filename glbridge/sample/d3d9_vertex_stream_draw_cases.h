static __attribute__((noinline)) void vertex_stream_draw_cases(void)
{
    D3DMATRIX identity;
    ZeroMemory(&identity, sizeof(identity));
    identity._11 = identity._22 = identity._33 = identity._44 = 1;
    OK(CALL(SetTransform)(device, D3DTS_WORLD, &identity));
    OK(CALL(SetTransform)(device, D3DTS_VIEW, &identity));
    OK(CALL(SetTransform)(device, D3DTS_PROJECTION, &identity));
    OK(CALL(SetRenderState)(device, D3DRS_LIGHTING, FALSE));
    OK(CALL(SetRenderState)(device, D3DRS_CLIPPING, TRUE));
    OK(CALL(SetRenderState)(device, D3DRS_CLIPPLANEENABLE, 0));
    Viewport viewport = { 0, 0, 128, 128, 0, 1 };
    OK(CALL(SetViewport)(device, &viewport));
    D3DVERTEXELEMENT9 elements[] = { { 3, 4, D3DDECLTYPE_FLOAT3, 0, D3DDECLUSAGE_POSITION, 0 }, { 15, 4, D3DDECLTYPE_FLOAT4, 0, D3DDECLUSAGE_COLOR, 0 }, D3DDECL_END() };
    IDirect3DVertexDeclaration9* declaration;
    OK(CALL(CreateVertexDeclaration)(device, elements, &declaration));
    OK(CALL(SetVertexDeclaration)(device, declaration));
    Buffer *positions, *colors, *unused;
    Indices* indices;
    void* mapped;
    OK(CALL(CreateVertexBuffer)(device, 100, D3DUSAGE_SOFTWAREPROCESSING, 0, D3DPOOL_SYSTEMMEM, &positions, NULL));
    OK(CALL(CreateVertexBuffer)(device, 24, D3DUSAGE_SOFTWAREPROCESSING, 0, D3DPOOL_SYSTEMMEM, &colors, NULL));
    OK(CALL(CreateVertexBuffer)(device, 16, D3DUSAGE_SOFTWAREPROCESSING, 0, D3DPOOL_SYSTEMMEM, &unused, NULL));
    OK(CALL(CreateIndexBuffer)(device, 6, D3DUSAGE_SOFTWAREPROCESSING, D3DFMT_INDEX16, D3DPOOL_SYSTEMMEM, &indices, NULL));
    float points[5][3] = { { 7, 0, .5f }, { -2, 0, .5f }, { 0, 3, .5f }, { .25f, 0, .5f }, { 0, 0, .5f } }, color[4] = { .25f, .5f, .75f, 1 };
    OK(BUF(Lock)(positions, 0, 100, &mapped, 0));
    FillMemory(mapped, 100, 0x63);
    for (unsigned i = 0; i < 5; ++i)
        CopyMemory((BYTE*)mapped + 8 + i * 20, points[i], 12);
    OK(BUF(Unlock)(positions));
    OK(BUF(Lock)(colors, 0, 24, &mapped, 0));
    FillMemory(mapped, 24, 0x63);
    CopyMemory((BYTE*)mapped + 8, color, 16);
    OK(BUF(Unlock)(colors));
    OK(IB(Lock)(indices, 0, 6, &mapped, 0));
    for (unsigned i = 0; i < 3; ++i)
        ((WORD*)mapped)[i] = 4;
    OK(IB(Unlock)(indices));
    OK(CALL(SetStreamSource)(device, 0, NULL, 0, 0));
    OK(CALL(SetStreamSource)(device, 3, positions, 4, 20));
    OK(CALL(SetStreamSource)(device, 15, colors, 4, 0));
    OK(CALL(SetIndices)(device, indices));
    OK(CALL(BeginScene)(device));
    D3DCLIPSTATUS9 status = { 0, 0xffffffffu };
    OK(CALL(SetClipStatus)(device, &status));
    OK(CALL(DrawPrimitive)(device, D3DPT_POINTLIST, 1, 3));
    OK(CALL(GetClipStatus)(device, &status));
    check(status.ClipUnion == 5 && status.ClipIntersection == 0, "draw multi-stream full range");
    status = (D3DCLIPSTATUS9) { 0, 0xffffffffu };
    OK(CALL(SetClipStatus)(device, &status));
    OK(CALL(DrawIndexedPrimitive)(device, D3DPT_TRIANGLELIST, -1, 2, 3, 0, 1));
    OK(CALL(GetClipStatus)(device, &status));
    check(status.ClipUnion == 5 && status.ClipIntersection == 0, "indexed status includes unreferenced range with signed base");
    float plane[4] = { -1, 0, 0, .1f };
    OK(CALL(SetClipPlane)(device, 0, plane));
    OK(CALL(SetRenderState)(device, D3DRS_CLIPPLANEENABLE, 1));
    status = (D3DCLIPSTATUS9) { 0, 0xffffffffu };
    OK(CALL(SetClipStatus)(device, &status));
    OK(CALL(DrawPrimitive)(device, D3DPT_POINTLIST, 3, 2));
    OK(CALL(GetClipStatus)(device, &status));
    check(status.ClipUnion == 64 && status.ClipIntersection == 0, "multi-stream draw world user plane");
    OK(CALL(SetRenderState)(device, D3DRS_CLIPPLANEENABLE, 0));
    /* The final element fits exactly even though stride padding is absent. */
    OK(CALL(DrawPrimitive)(device, D3DPT_POINTLIST, 4, 1));
    status = (D3DCLIPSTATUS9) { 0x80000000u, 0x80000000u };
    OK(CALL(SetClipStatus)(device, &status));
    OK(CALL(SetStreamSource)(device, 15, colors, 5, 0));
    check(FAILED(CALL(DrawPrimitive)(device, D3DPT_POINTLIST, 1, 3)), "draw checks late constant stream bounds");
    check(FAILED(CALL(DrawIndexedPrimitive)(device, D3DPT_TRIANGLELIST, -1, 2, 3, 0, 1)), "indexed draw checks late stream bounds");
    OK(CALL(SetStreamSource)(device, 15, colors, 4, 0));
    OK(BUF(Lock)(colors, 0, 24, &mapped, 0));
    check(FAILED(CALL(DrawPrimitive)(device, D3DPT_POINTLIST, 1, 3)), "draw checks locked used stream");
    OK(BUF(Unlock)(colors));
    check(FAILED(CALL(DrawIndexedPrimitive)(device, D3DPT_TRIANGLELIST, -3, 2, 3, 0, 1)), "negative resulting source vertex refused");
    check(FAILED(CALL(DrawIndexedPrimitive)(device, D3DPT_TRIANGLELIST, 0, 0xffffffffu, 2, 0, 1)), "declared index range overflow refused");
    OK(IB(Lock)(indices, 0, 6, &mapped, 0));
    ((WORD*)mapped)[2] = 5;
    OK(IB(Unlock)(indices));
    check(FAILED(CALL(DrawIndexedPrimitive)(device, D3DPT_TRIANGLELIST, -1, 2, 3, 0, 1)), "software draw checks actual raw index end");
    OK(CALL(GetClipStatus)(device, &status));
    check(status.ClipUnion == 0x80000000u && status.ClipIntersection == 0x80000000u, "failed draw preserves accumulated status");
    OK(IB(Lock)(indices, 0, 6, &mapped, 0));
    ((WORD*)mapped)[2] = 4;
    OK(IB(Unlock)(indices));
    OK(CALL(SetStreamSource)(device, 0, unused, 0, 4));
    OK(BUF(Lock)(unused, 0, 16, &mapped, 0));
    OK(CALL(DrawPrimitive)(device, D3DPT_POINTLIST, 4, 1));
    OK(BUF(Unlock)(unused));
    OK(CALL(SetStreamSource)(device, 0, NULL, 0, 0));
    OK(CALL(SetStreamSource)(device, 3, positions, 4, 0));
    status = (D3DCLIPSTATUS9) { 0, 0xffffffffu };
    OK(CALL(SetClipStatus)(device, &status));
    OK(CALL(DrawPrimitive)(device, D3DPT_POINTLIST, 0xffffffffu, 2));
    OK(CALL(GetClipStatus)(device, &status));
    check(status.ClipUnion == 2 && status.ClipIntersection == 2, "constant position draw ignores huge source index");
    OK(CALL(SetStreamSource)(device, 3, positions, 4, 20));
    OK(CALL(SetStreamSourceFreq)(device, 0, D3DSTREAMSOURCE_INDEXEDDATA | 4));
    OK(CALL(SetStreamSourceFreq)(device, 15, D3DSTREAMSOURCE_INSTANCEDATA | 3));
    OK(CALL(DrawIndexedPrimitive)(device, D3DPT_TRIANGLELIST, -1, 2, 3, 0, 1));
    check(FAILED(CALL(GetClipStatus)(device, &status)), "unsupported CPU instancing status never appears current");
    OK(CALL(SetStreamSourceFreq)(device, 0, 1));
    OK(CALL(SetStreamSourceFreq)(device, 15, 1));
    OK(CALL(SetRenderState)(device, D3DRS_CLIPPING, FALSE));
    OK(CALL(DrawPrimitive)(device, D3DPT_POINTLIST, 4, 1));
    OK(CALL(GetClipStatus)(device, &status));
    check(status.ClipUnion == 0 && status.ClipIntersection == 0, "disabled clipping restores valid multi-stream status");
    OK(CALL(SetRenderState)(device, D3DRS_CLIPPING, TRUE));
    Buffer* processed;
    OK(CALL(CreateVertexBuffer)(device, 32, D3DUSAGE_SOFTWAREPROCESSING, 4, D3DPOOL_SYSTEMMEM, &processed, NULL));
    OK(CALL(ProcessVertices)(device, 0, 0, 2, processed, NULL, 0));
    D3DVERTEXELEMENT9 screen_elements[] = { { 3, 0, D3DDECLTYPE_FLOAT4, 0, D3DDECLUSAGE_POSITIONT, 0 }, { 15, 4, D3DDECLTYPE_FLOAT4, 0, D3DDECLUSAGE_COLOR, 0 }, D3DDECL_END() };
    IDirect3DVertexDeclaration9* screen_decl;
    OK(CALL(CreateVertexDeclaration)(device, screen_elements, &screen_decl));
    OK(CALL(SetVertexDeclaration)(device, screen_decl));
    OK(CALL(SetStreamSource)(device, 3, processed, 0, 16));
    check(FAILED(CALL(DrawPrimitive)(device, D3DPT_POINTLIST, 0, 2)), "processed multi-stream screen records require a remapping clip emitter");
    OK(BUF(Lock)(processed, 0, 32, &mapped, 0));
    for (unsigned i = 0; i < 2; ++i) {
        float screen[4] = { 32.0f + i * 32, 32, .5f, 1 };
        CopyMemory((BYTE*)mapped + i * 16, screen, 16);
    }
    OK(BUF(Unlock)(processed));
    status = (D3DCLIPSTATUS9) { 0x1234u, 0x5678u };
    OK(CALL(SetClipStatus)(device, &status));
    OK(CALL(DrawPrimitive)(device, D3DPT_POINTLIST, 0, 2));
    OK(CALL(GetClipStatus)(device, &status));
    check(status.ClipUnion == 0x1234u && status.ClipIntersection == 0x5678u, "raw multi-stream POSITIONT skips clip processing");
    IDirect3DVertexDeclaration9_Release(screen_decl);
    BUF(Release)(processed);
    OK(CALL(EndScene)(device));
    for (unsigned i = 0; i < 16; ++i)
        OK(CALL(SetStreamSource)(device, i, NULL, 0, 0));
    OK(CALL(SetIndices)(device, NULL));
    IDirect3DVertexDeclaration9_Release(declaration);
    BUF(Release)(positions);
    BUF(Release)(colors);
    BUF(Release)(unused);
    IB(Release)(indices);
    report("PASS real XP multi-stream draws: absent/unused stream zero, full declared indexed range, negative base, world planes, final attribute bounds, constant position, instancing bounds and atomic status failures");
}

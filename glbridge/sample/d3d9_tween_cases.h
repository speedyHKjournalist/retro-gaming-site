static void d3d9_tween_checks(void)
{
    D3DCAPS9 caps;
    check(SUCCEEDED(CALL(GetDeviceCaps)(device, &caps)) && (caps.VertexProcessingCaps & D3DVTXPCAPS_TWEENING), "device declares verified tweening");
    check(SUCCEEDED(FACT(GetDeviceCaps)(factory, 0, D3DDEVTYPE_HAL, &caps)) && (caps.VertexProcessingCaps & D3DVTXPCAPS_TWEENING), "factory declares verified tweening");
    IDirect3DStateBlock9 *baseline, *recorded;
    check(SUCCEEDED(CALL(CreateStateBlock)(device, D3DSBT_ALL, &baseline)), "tween baseline");
    IDirect3DVertexDeclaration9 *declaration, *missing, *position_only, *normal_only;
    D3DVERTEXELEMENT9 elements[] = { { 0, 0, D3DDECLTYPE_FLOAT3, 0, D3DDECLUSAGE_POSITION, 0 }, { 0, 12, D3DDECLTYPE_FLOAT3, 0, D3DDECLUSAGE_NORMAL, 0 }, { 1, 0, D3DDECLTYPE_FLOAT3, 0, D3DDECLUSAGE_POSITION, 1 }, { 1, 12, D3DDECLTYPE_FLOAT3, 0, D3DDECLUSAGE_NORMAL, 1 }, D3DDECL_END() };
    check(SUCCEEDED(CALL(CreateVertexDeclaration)(device, elements, &declaration)), "tween declaration");
    D3DVERTEXELEMENT9 reduced[] = { elements[0], elements[1], D3DDECL_END(), D3DDECL_END() };
    check(SUCCEEDED(CALL(CreateVertexDeclaration)(device, reduced, &missing)), "tween missing declaration");
    reduced[2] = elements[2];
    check(SUCCEEDED(CALL(CreateVertexDeclaration)(device, reduced, &position_only)), "tween second position declaration");
    reduced[2] = elements[3];
    check(SUCCEEDED(CALL(CreateVertexDeclaration)(device, reduced, &normal_only)), "tween second normal declaration");
    Buffer *primary, *secondary, *output;
    float first[12] = { -.5f, 0, .25f, -1, 0, 0, -.25f, 0, .25f, -1, 0, 0 }, second[6] = { .5f, 0, .75f, 1, 0, 0 };
    create_buffer(0, sizeof(first), &primary);
    create_buffer(0, sizeof(second), &secondary);
    create_buffer(D3DFVF_XYZRHW | D3DFVF_DIFFUSE | D3DFVF_SPECULAR | D3DFVF_TEX1 | D3DFVF_TEXCOORDSIZE4(0), 2 * sizeof(Output), &output);
    CopyMemory(lock_buffer(primary), first, sizeof(first));
    check(SUCCEEDED(BUF(Unlock)(primary)), "tween primary upload");
    CopyMemory(lock_buffer(secondary), second, sizeof(second));
    check(SUCCEEDED(BUF(Unlock)(secondary)), "tween secondary upload");
    check(SUCCEEDED(CALL(SetStreamSource)(device, 0, primary, 0, 24)) && SUCCEEDED(CALL(SetStreamSource)(device, 1, secondary, 0, 0)) && SUCCEEDED(CALL(SetVertexDeclaration)(device, declaration)), "tween bind multi and constant streams");
    D3DMATRIX matrix;
    identity(&matrix);
    matrix._11 = 2;
    check(SUCCEEDED(CALL(SetTransform)(device, D3DTS_WORLD, &matrix)), "tween world");
    identity(&matrix);
    matrix._42 = .25f;
    check(SUCCEEDED(CALL(SetTransform)(device, D3DTS_VIEW, &matrix)), "tween view");
    identity(&matrix);
    matrix._33 = .5f;
    check(SUCCEEDED(CALL(SetTransform)(device, D3DTS_PROJECTION, &matrix)), "tween projection");
    Material material;
    ZeroMemory(&material, sizeof(material));
    material.Diffuse.r = material.Diffuse.g = material.Diffuse.b = material.Diffuse.a = 1;
    check(SUCCEEDED(CALL(SetMaterial)(device, &material)), "tween material");
    Light lamp;
    ZeroMemory(&lamp, sizeof(lamp));
    lamp.Type = D3DLIGHT_DIRECTIONAL;
    lamp.Direction.x = -1;
    lamp.Diffuse.r = lamp.Diffuse.g = lamp.Diffuse.b = 1;
    light(&lamp);
    state(D3DRS_LIGHTING, TRUE);
    state(D3DRS_COLORVERTEX, FALSE);
    state(D3DRS_AMBIENT, 0);
    state(D3DRS_DIFFUSEMATERIALSOURCE, D3DMCS_MATERIAL);
    state(D3DRS_NORMALIZENORMALS, FALSE);
    state(D3DRS_SPECULARENABLE, FALSE);
    state(D3DRS_VERTEXBLEND, D3DVBF_TWEENING);
    state(D3DRS_INDEXEDVERTEXBLENDENABLE, TRUE);
    float_state(D3DRS_TWEENFACTOR, .75f);
    state(D3DRS_FOGVERTEXMODE, D3DFOG_LINEAR);
    state(D3DRS_RANGEFOGENABLE, FALSE);
    float_state(D3DRS_FOGSTART, 0);
    float_state(D3DRS_FOGEND, 1);
    state(D3DRS_CLIPPLANEENABLE, 0);
    state(D3DRS_CLIPPING, TRUE);
    texture_state(0x20000, 0);
    FillMemory(lock_buffer(output), 2 * sizeof(Output), 0xa5);
    check(SUCCEEDED(BUF(Unlock)(output)), "tween prepare output");
    check(SUCCEEDED(CALL(ProcessVertices)(device, 0, 0, 2, output, NULL, D3DPV_DONOTCOPYDATA)), "tween ProcessVertices");
    Output result[2];
    CopyMemory(result, lock_buffer(output), sizeof(result));
    check(SUCCEEDED(BUF(Unlock)(output)), "tween read output");
    check(result[0].x == 48 && result[1].x == 52 && result[0].y == 24 && result[0].z == .3125f && result[0].rhw == 1, "tween position before world/view/projection");
    check(result[0].diffuse == 0xff404040u && (result[0].specular >> 24) == 96, "tween normal before lighting and fog");
    check(result[0].tex[0] == .5f && result[0].tex[1] == .25f && result[0].tex[2] == .625f, "tween camera-space generated coordinates");
    state(D3DRS_NORMALIZENORMALS, TRUE);
    check(SUCCEEDED(CALL(ProcessVertices)(device, 0, 0, 1, output, NULL, 0)), "normalized tween process");
    Output value = *(Output*)lock_buffer(output);
    check(SUCCEEDED(BUF(Unlock)(output)) && value.diffuse == 0xffffffffu, "tween normalized after interpolation and normal matrix");
    state(D3DRS_NORMALIZENORMALS, FALSE);
    check(SUCCEEDED(CALL(SetVertexDeclaration)(device, normal_only)) && SUCCEEDED(CALL(ProcessVertices)(device, 0, 0, 1, output, NULL, 0)), "normal-only tween process");
    value = *(Output*)lock_buffer(output);
    check(SUCCEEDED(BUF(Unlock)(output)) && value.x == 0 && value.diffuse == 0xff404040u, "independent secondary normal");
    check(SUCCEEDED(CALL(SetVertexDeclaration)(device, position_only)) && SUCCEEDED(CALL(ProcessVertices)(device, 0, 0, 1, output, NULL, 0)), "position-only tween process");
    value = *(Output*)lock_buffer(output);
    check(SUCCEEDED(BUF(Unlock)(output)) && value.x == 48 && value.diffuse == 0xff000000u, "independent secondary position");
    check(SUCCEEDED(CALL(SetVertexDeclaration)(device, declaration)) && SUCCEEDED(CALL(BeginStateBlock)(device)), "record tween factor");
    float_state(D3DRS_TWEENFACTOR, .25f);
    DWORD factor;
    check(SUCCEEDED(CALL(GetRenderState)(device, D3DRS_TWEENFACTOR, &factor)) && factor == 0x3f400000u, "recording leaves tween factor live");
    check(SUCCEEDED(CALL(EndStateBlock)(device, &recorded)) && SUCCEEDED(IDirect3DStateBlock9_Apply(recorded)), "apply tween factor");
    IDirect3DStateBlock9_Release(recorded);
    D3DCLIPSTATUS9 status = { 0, 0xffffffffu };
    float plane[4] = { 1, 0, 0, -.25f };
    check(SUCCEEDED(CALL(SetClipPlane)(device, 0, plane)) && SUCCEEDED(CALL(SetClipStatus)(device, &status)), "tween user plane");
    state(D3DRS_CLIPPLANEENABLE, 1);
    check(SUCCEEDED(CALL(ProcessVertices)(device, 0, 0, 2, output, NULL, 0)) && SUCCEEDED(CALL(GetClipStatus)(device, &status)) && (status.ClipUnion & D3DCS_PLANE0) && (status.ClipIntersection & D3DCS_PLANE0), "tween precedes user-plane ClipStatus");
    state(D3DRS_CLIPPLANEENABLE, 0);
    FillMemory(lock_buffer(output), 2 * sizeof(Output), 0xa5);
    check(SUCCEEDED(BUF(Unlock)(output)), "tween atomic output seed");
    check(SUCCEEDED(CALL(SetStreamSource)(device, 1, secondary, 1, 0)) && FAILED(CALL(ProcessVertices)(device, 0, 0, 2, output, NULL, 0)), "tween short constant stream refused");
    check(SUCCEEDED(CALL(SetStreamSource)(device, 1, secondary, 0, 0)) && SUCCEEDED(CALL(SetVertexDeclaration)(device, missing)) && FAILED(CALL(ProcessVertices)(device, 0, 0, 2, output, NULL, 0)), "tween missing secondary channels refused");
    BYTE* bytes = lock_buffer(output);
    for (unsigned i = 0; i < 2 * sizeof(Output); ++i)
        check(bytes[i] == 0xa5, "failed tween preserves output");
    check(SUCCEEDED(BUF(Unlock)(output)), "tween atomic output unlock");
    check(SUCCEEDED(IDirect3DStateBlock9_Apply(baseline)), "restore tween baseline");
    IDirect3DStateBlock9_Release(baseline);
    IDirect3DVertexDeclaration9_Release(declaration);
    IDirect3DVertexDeclaration9_Release(missing);
    IDirect3DVertexDeclaration9_Release(position_only);
    IDirect3DVertexDeclaration9_Release(normal_only);
    BUF(Release)(primary);
    BUF(Release)(secondary);
    BUF(Release)(output);
    report("PASS D3D9 CPU tween: positions/normals, lighting/fog/texgen, multi/constant streams, state-block factor, user-plane ClipStatus and atomic failure");
}
